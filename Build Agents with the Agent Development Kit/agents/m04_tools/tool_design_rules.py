# Code 3. ルール 2 ― docstring が最も重要
# ---------------------------------------------------------------------
# docstring に必ず書く 3 点
#   1. tool の目的
#   2. 各パラメータが何を期待しているのか
#   3. 戻り値をどう解釈するのか（エラーケースを含む）  ← 一番抜けやすい
# =====================================================================
