#!/usr/bin/env bash
# =====================================================================
# M3 ― Running Your First Agent：コマンド集
# ---------------------------------------------------------------------
# このファイルは「実行する台本」ではなく、講義中に 1 つずつコピーして
# 見せるためのコマンド集です。すべて agents/ フォルダで実行します。
#   cd agents
# =====================================================================

# 誤って丸ごと実行しないためのガード（adk web などは起動したまま戻らないため）
echo "このファイルはコマンド集です。必要な行をコピーして実行してください。"; exit 0

# ---------------------------------------------------------------------
# Code 1. adk create でプロジェクトを開始する
# ---------------------------------------------------------------------
# 対話形式でモデル名やバックエンドを聞かれ、3 ファイルが生成される。
# （--type config を付けると agent.py の代わりに root_agent.yaml 形式の
#   雛形になるが、実験的機能なので本コースではコード形式を使う）
adk create support_agent

# ---------------------------------------------------------------------
# Code 4. 3 つの実行モード
# ---------------------------------------------------------------------
# ① adk run <agent フォルダ> … ターミナルに REPL が起動する。
#    どの tool が呼ばれ何を返したかも表示される。手早い動作確認向け。
adk run m03_running_agent

#    メッセージを 1 つだけ投げて終了する使い方もできる
adk run m03_running_agent "A-1001 の残高を教えて"

# ② adk web [agents_dir] … http://localhost:8000 にブラウザ UI。
#    左がチャット、右がトレースビュー。開発中のメインはこれ。
adk web .

# ③ adk api_server [agents_dir] … 応答をストリーミングする HTTP サーバー。
#    agent を REST API として別アプリに組み込むときに使う。
adk api_server .

